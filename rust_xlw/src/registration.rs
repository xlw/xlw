// --- Argument Metadata ---

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RustArgumentMetadata {
    pub name: String,          // Name of the argument in Rust
    pub description: String,   // Description for Excel function wizard
    pub type_code: String,     // Excel type code (e.g., "P", "B", "E%")
                               // The % indicates pass-by-value for numeric types for Excel.
                               // "E" is short int (our c_short for xltypeInt)
                               // "P" is LPXLOPER12
                               // "B" is double
                               // Other codes exist for strings, bools, arrays, etc.
    pub default_value: Option<String>, // Optional default value as a string representation
}

// --- Function Metadata ---

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RustFunctionMetadata {
    pub rust_name: String,        // The internal name of the Rust function (e.g., "my_add_fn")
    pub excel_name: String,       // Name to be registered in Excel (e.g., "MyAddFunction")
    pub description: String,      // Description for Excel function wizard
    pub category: String,         // Category for Excel function wizard (e.g., "My Rust Functions")
    pub help_topic: String,       // Help topic URL/ID (optional)

    pub arguments: Vec<RustArgumentMetadata>, // List of argument metadata

    pub return_type_code: String, // Excel type code for the return value (e.g., "P", "B", "E%")
                                  // This tells Excel what the function returns.
                                  // If it returns LPXLOPER12, this is usually "P".
                                  // If it returns double directly, it is "B".
                                  // If it returns void (for commands), it might be specific or implicit.

    pub is_volatile: bool,        // Is the function volatile?
    pub is_thread_safe: bool,     // Is the function thread-safe (Excel 2007+)?
    pub is_cluster_safe: bool,    // Is the function cluster-safe (HPC)? (Excel 2007+)
    pub is_macro_sheet_equivalent: bool, // Can be called from macro sheets?
    pub is_asynchronous: bool,    // Is it an asynchronous function (Excel 2010+)?

    // For direct registration of Rust functions that take LPXLOPER12 and return LPXLOPER12:
    // pub function_pointer: Option<unsafe extern "C" fn(LPXLOPER12, ...) -> LPXLOPER12>,
    // For now, we assume the interface generator (macros) will create wrappers,
    // so we might not store the direct function pointer here, but rather the rust_name
    // which the macro uses to call the original function.
    // The name of the extern "C" wrapper generated by a macro could be stored here too.
    pub wrapper_function_name: String, // Name of the extern "C" wrapper function to register
}

impl RustFunctionMetadata {
    /// Helper to generate the full Excel registration signature string for arguments.
    /// Example: "PBB%" for (LPXLOPER12, double, double by value).
    pub fn get_argument_signature(&self) -> String {
        self.arguments.iter().map(|arg| arg.type_code.clone()).collect::<String>()
    }
}

// --- Global Static Registry for Function Metadata ---

lazy_static! {
    /// Global registry to store metadata for all functions to be registered with Excel.
    /// Access to this registry is protected by a Mutex to allow safe modification
    /// from multiple procedural macros (which effectively run at compile time or via `ctor`).
    static ref FUNCTION_REGISTRY: Mutex<Vec<RustFunctionMetadata>> = Mutex::new(Vec::new());
}

/// Adds function metadata to the global registry.
/// This function is intended to be called by code generated by procedural macros
/// or during a static initialization phase.
///
/// # Panics
/// Panics if the Mutex is poisoned (which indicates a previous panic while locked).
pub fn add_function_to_registry(metadata: RustFunctionMetadata) {
    let mut registry = FUNCTION_REGISTRY.lock().expect("FUNCTION_REGISTRY Mutex poisoned");
    // TODO: Potentially check for duplicate function names (Excel names) here
    registry.push(metadata);
}

/// Retrieves a clone of all function metadata currently in the registry.
/// This is typically called by `xlAutoOpen` to perform the registrations.
///
/// # Panics
/// Panics if the Mutex is poisoned.
pub fn get_function_registrations() -> Vec<RustFunctionMetadata> {
    let registry = FUNCTION_REGISTRY.lock().expect("FUNCTION_REGISTRY Mutex poisoned");
    registry.clone() // Clone the Vec to release the lock quickly
}

