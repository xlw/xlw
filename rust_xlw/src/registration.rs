// --- Function to perform actual Excel registrations ---

use crate::ffi::{self, Excel12, XLOPER12, XLOPER12_val, LPXLOPER12, XLTYPE_STR, XLTYPE_NUM, XLTYPE_INT, XLTYPE_BOOL, XLTYPE_MISSING, WCHAR};
use crate::rust_oper::RustOper; // For creating XLOPER12s easily
use std::os::raw::c_int;
// use std::ffi::CString; // Not needed for Pascal strings

/// Converts a Rust string to a Pascal string suitable for Excel API (LPWSTR style).
/// Output Vec<WCHAR> represents the Pascal string (length-prefixed UTF-16).
fn to_pascal_wide_string(s: &str) -> Vec<WCHAR> {
    let mut wide_chars: Vec<WCHAR> = s.encode_utf16().collect();
    let len = wide_chars.len();

    if len > 255 {
        wide_chars.truncate(255);
        wide_chars.insert(0, 255 as WCHAR);
    } else {
        wide_chars.insert(0, len as WCHAR);
    }
    wide_chars
}


/// Registers all functions currently in the FUNCTION_REGISTRY with Excel.
/// This is typically called from `xlAutoOpen`.
pub fn perform_registrations() -> Result<(), String> {
    let registrations = get_function_registrations();
    if registrations.is_empty() {
        eprintln!("[rust_xlw_reg] No functions found in registry.");
        return Ok(());
    }

    eprintln!("[rust_xlw_reg] Attempting to register {} functions...", registrations.len());

    let mut xll_path_oper = RustOper::new_str("");

    for metadata in registrations {
        eprintln!("[rust_xlw_reg] Registering: {}", metadata.excel_name);

        let mut proc_name_oper = RustOper::new_str(&metadata.wrapper_function_name);
        let arg_types_str = metadata.get_argument_signature() + &metadata.return_type_code;
        let mut arg_types_oper = RustOper::new_str(&arg_types_str);
        let mut excel_name_oper = RustOper::new_str(&metadata.excel_name);

        let arg_names_str = metadata.arguments.iter().map(|a| a.name.clone()).collect::<Vec<String>>().join(",");
        let mut arg_names_oper = RustOper::new_str(&arg_names_str);

        let mut fn_type_oper = RustOper::new_num(1.0); // 1 for function
        let mut category_oper = RustOper::new_str(&metadata.category);
        let mut help_topic_oper = RustOper::new_str(&metadata.help_topic);
        let mut fn_description_oper = RustOper::new_str(&metadata.description);
        let mut shortcut_key_oper = RustOper::new_missing(); // Shortcut Key (missing)

        let mut arg_desc_opers_rust: Vec<RustOper> = Vec::new();
        if !metadata.arguments.is_empty() {
            for arg_meta in &metadata.arguments {
                arg_desc_opers_rust.push(RustOper::new_str(&arg_meta.description));
            }
        }

        let mut arg_descriptions_array_oper = if !arg_desc_opers_rust.is_empty() {
            let num_args = arg_desc_opers_rust.len() as u16;
            let mut temp_array = RustOper::new_array(1, num_args).map_err(|e| e.to_string())?;
            for (i, desc_oper) in arg_desc_opers_rust.into_iter().enumerate() {
                temp_array.set_element(0, i as u16, desc_oper).map_err(|e| e.to_string())?;
            }
            temp_array
        } else {
            RustOper::new_missing()
        };

        let mut result_oper = RustOper::new();

        // Create a vector of mutable pointers to the XLOPER12s
        // These RustOpers live on the stack for the duration of the Excel12 call.
        let mut args_to_xlfregister_ptrs: Vec<LPXLOPER12> = unsafe { vec![
            xll_path_oper.as_lpxloper12_mut(),
            proc_name_oper.as_lpxloper12_mut(),
            arg_types_oper.as_lpxloper12_mut(),
            excel_name_oper.as_lpxloper12_mut(),
            arg_names_oper.as_lpxloper12_mut(),
            fn_type_oper.as_lpxloper12_mut(),
            category_oper.as_lpxloper12_mut(),
            shortcut_key_oper.as_lpxloper12_mut(),
            help_topic_oper.as_lpxloper12_mut(),
            fn_description_oper.as_lpxloper12_mut(),
            arg_descriptions_array_oper.as_lpxloper12_mut()
        ]};

        let ret_code = unsafe {
            Excel12(
                ffi::XLF_REGISTER,
                result_oper.as_lpxloper12_mut(),
                args_to_xlfregister_ptrs.len() as c_int,
                args_to_xlfregister_ptrs.as_mut_ptr() // Pass pointer to the vector of pointers
            )
        };

        if ret_code != ffi::XLRET_SUCCESS {
            let err_msg = format!("Failed to register function '{}'. Excel12(xlfRegister) returned code: {}. ResultOper type: {}, value: {:?}",
                                metadata.excel_name, ret_code, result_oper.type_name(), result_oper.as_f64().ok());
            eprintln!("[rust_xlw_reg] {}", err_msg);
        } else {
             eprintln!("[rust_xlw_reg] Successfully registered '{}' (or it was already registered with this signature)", metadata.excel_name);
             if result_oper.is_num() {
                eprintln!("[rust_xlw_reg] Registration ID: {}", result_oper.as_f64().unwrap_or_default());
             }
        }
    }
    Ok(())
}

/// Unregisters all functions currently in the FUNCTION_REGISTRY from Excel.
/// This is typically called from `xlAutoClose`.
pub fn perform_deregistrations() -> Result<(), String> {
    let registrations = get_function_registrations(); // Re-fetch the list
    if registrations.is_empty() {
        eprintln!("[rust_xlw_reg] No functions found in registry to deregister.");
        return Ok(());
    }

    eprintln!("[rust_xlw_reg] Attempting to deregister {} functions...", registrations.len());

    for metadata in registrations {
        eprintln!("[rust_xlw_reg] Deregistering: {}", metadata.excel_name);

        // Argument for Excel12(xlfUnregister, ...):
        // 1. Function Name (LPXLOPER12) or Registration ID (LPXLOPER12 of type num)
        // We will use the function name for simplicity here.

        let mut excel_name_oper = RustOper::new_str(&metadata.excel_name);
        let mut result_oper = RustOper::new(); // To receive the result (usually TRUE/FALSE or error)

        let ret_code = unsafe {
            Excel12(
                ffi::XLF_UNREGISTER,
                result_oper.as_lpxloper12_mut(),
                1, // Number of arguments to xlfUnregister
                excel_name_oper.as_lpxloper12_mut()
            )
        };

        if ret_code != ffi::XLRET_SUCCESS || !result_oper.as_bool().unwrap_or(false) {
            // If Excel12 failed OR if result_oper is FALSE (meaning unregister failed logically)
            let err_msg = format!("Failed to deregister function '{}'. Excel code: {}. Result: {:?}",
                                metadata.excel_name, ret_code, result_oper);
            eprintln!("[rust_xlw_reg] {}", err_msg);
            // Collect errors or handle as needed
        } else {
            eprintln!("[rust_xlw_reg] Successfully deregistered '{}'", metadata.excel_name);
        }
    }
    Ok(())
}
